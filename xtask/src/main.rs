fn record_trace_label_is_safe(label: &str) -> bool {
    !label.is_empty()
        && label
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte == b'-')
}

/// Emit only an allowlisted, static recorder progress label when explicitly
/// requested. Labels must never carry remote values or error details.
fn record_trace(label: &'static str) {
    debug_assert!(RECORD_TRACE_LABELS.contains(&label));
    debug_assert!(record_trace_label_is_safe(label));
    if std::env::var("ELASTICCTL_RECORD_TRACE").ok().as_deref() == Some("1") {
        eprintln!("record step: {label}");
    }
}

/// Recorder errors can carry live object ids in a server message or body.
/// Preserve only their classification and status at public error boundaries.
fn safe_recording_transport_error(
    context: &'static str,
    error: elasticctl_core::Error,
) -> elasticctl_core::Error {
    match error.http_status {
        Some(status) => elasticctl_core::Error::with_status(error.kind, status, context),
        None => elasticctl_core::Error::new(error.kind, context),
    }
}

fn safe_recording_error_summary(error: &elasticctl_core::Error) -> String {
    let status = error
        .http_status
        .map_or_else(|| "none".to_string(), |status| status.to_string());
    format!("class={} status={status}", error.kind.as_str())
}

fn dashboard_transport<T>(
    context: &'static str,
    result: elasticctl_core::Result<T>,
) -> elasticctl_core::Result<T> {
    result.map_err(|error| safe_recording_transport_error(context, error))
}

/// The only recorder flavor that starts headless needs a profile activation
/// before the later alert-assignment probe can resolve an assignee. Keep the
/// decision pure so tests never race on process environment variables.
struct TraditionalRecorderLogin<'a> {
    username: &'a str,
    password: &'a str,
}

fn traditional_recorder_login_inputs<'a>(
    flavor: Option<&str>,
    username: Option<&'a str>,
    password: Option<&'a str>,
) -> elasticctl_core::Result<Option<TraditionalRecorderLogin<'a>>> {
    if flavor != Some("traditional") {
        return Ok(None);
    }
    let username = username
        .filter(|value| !value.trim().is_empty())
        .ok_or_else(|| {
            recording_error("ELASTICCTL_USERNAME is required for traditional fixture recording")
        })?;
    let password = password
        .filter(|value| !value.trim().is_empty())
        .ok_or_else(|| {
            recording_error("ELASTICCTL_PASSWORD is required for traditional fixture recording")
        })?;
    Ok(Some(TraditionalRecorderLogin { username, password }))
}

async fn activate_traditional_recorder_profile() -> elasticctl_core::Result<()> {
    let flavor = std::env::var("ELASTICCTL_FIXTURE_FLAVOR").ok();
    let username = std::env::var("ELASTICCTL_USERNAME").ok();
    let password = std::env::var("ELASTICCTL_PASSWORD").ok();
    let login = traditional_recorder_login_inputs(
        flavor.as_deref(),
        username.as_deref(),
        password.as_deref(),
    )?;
    let Some(login) = login else {
        return Ok(());
    };
    let kibana_url = std::env::var("ELASTICCTL_KIBANA_URL").map_err(|_| {
        recording_error("ELASTICCTL_KIBANA_URL is required for traditional fixture recording")
    })?;
    activation::activate_profile(&kibana_url, login.username, login.password)
        .await
        .map_err(|error| {
            safe_recording_transport_error("traditional profile activation failed", error)
        })
}

